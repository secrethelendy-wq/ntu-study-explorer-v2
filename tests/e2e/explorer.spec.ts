  await page.getByRole('button',{name:'帶電腦去',exact:true}).click()
  const expected=spaces.filter(s=>s.outlets.coverage==='all'||s.outlets.coverage==='partial')
  await expect(page.locator('.space-card')).toHaveCount(13)
  expect(await page.locator('.space-card').evaluateAll(cards=>cards.map(c=>c.getAttribute('data-space-id')))).toEqual(expected.map(s=>s.id))
