  await page.getByRole('searchbox',{name:'搜尋自習空間'}).fill('綜合')
  await expect(page.locator('.space-card')).toHaveCount(2)
  await page.getByRole('button',{name:'清除搜尋',exact:true}).click()
  await expect(page.locator('.space-card')).toHaveCount(13)
  await page.getByRole('button',{name:'確定',exact:true}).click()
  await expect(page.locator('.space-card')).toHaveCount(2)
  await openFilters(page)
  await page.locator('.filters-panel').getByRole('button',{name:'清除全部篩選',exact:true}).click()
  await expect(page.locator('.space-card')).toHaveCount(15)
  await expect(page.getByLabel('風扇',{exact:true})).toHaveValue('')
  await expect(page.getByLabel('插座',{exact:true})).toHaveValue('')
